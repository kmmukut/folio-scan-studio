@pytest.fixture
def fresh(tmp_path, monkeypatch):
    monkeypatch.setattr(web, 'DATA_DIR', tmp_path)
    monkeypatch.setattr(web, 'JOBS_DIR', tmp_path / 'jobs')
    monkeypatch.setattr(web, 'PREVIEW_ROOT', tmp_path / 'print-previews')
    monkeypatch.setattr(web, 'DEVICE', '')
    monkeypatch.setenv('FOLIO_AIRSCAN_DISCOVERY', 'off')
    monkeypatch.setenv('SCAN_STUDIO_ADMIN_PASSWORD', 'test-password-12345678')
    monkeypatch.setattr(devices, 'list_cups_queues', lambda server: [])

    def sane_listed():
        # A new scanimage process reads /data/managed-airscan.conf. Mimic that
        # registry without involving a physical network scanner in CI.
        entries=json.loads((tmp_path/'devices.json').read_text())['scanners']
        return [{'sane_name':f"airscan:w0:Folio-{e['id']} {e['name']}",
                 'description':f"WSD scanner ip={e['ip']}"}
                for e in entries if e['kind']=='managed' and e.get('enabled',True)]
    monkeypatch.setattr(devices, 'listed_sane_devices', sane_listed)
    monkeypatch.setattr(devices, 'scanner_capabilities',
                        lambda d: {'available':True,'sources':['Flatbed','ADF'],
                                   'modes':['Color','Gray'],
                                   'resolutions':[75,150,200,300]})
    security._guest_submissions.clear();security._global_submissions.clear()
    with TestClient(web.app) as client:
        signed=client.post('/api/auth/login',json={'username':'admin','password':'test-password-12345678'})
        assert signed.status_code==200,signed.text
        client.headers['x-csrf-token']=signed.json()['csrf']
        yield client, tmp_path


def test_first_run_no_scanner_no_compose_override(fresh):
    client,tmp=fresh
    conf=client.get('/api/admin/devices').json()
    assert conf['scanners']==[]
    assert conf['default_scanner'] is None
    assert client.get('/api/scanner').json()['connected'] is False
    assert client.get('/api/scanners').json()['scanners']==[]
    cfg=tmp/'managed-airscan.conf'
    assert cfg.exists()
    assert cfg.read_text().startswith('# Generated by Folio')
    assert 'discovery = disable' in cfg.read_text()
    assert 'Samsung' not in cfg.read_text()
    job=client.post('/api/jobs',json={'title':'New scan'}).json()['id']
    fail=client.post(f'/api/jobs/{job}/scan',json={'source':'ADF','mode':'Color','resolution':300,'count':1})
    assert fail.status_code==404 and 'No scanner configured' in fail.text


def test_add_edit_delete_scanner_without_restart(fresh):
    client,tmp=fresh
    added=client.post('/api/admin/scanners',json={
        'name':'Samsung M2885FW','ip':'192.0.2.124',
        'protocol':'WSD','port':8018,'path':'/wsd/scan'})
    assert added.status_code==201,added.text
    device=added.json()
    assert device['kind']=='managed'
    scanner_id=device['id']
    conf=tmp/'managed-airscan.conf'
    assert '"Folio-'+scanner_id+' Samsung M2885FW" = http://192.0.2.124:8018/wsd/scan, WSD' in conf.read_text()
    assert client.get('/api/scanners').json()['default']==scanner_id
    assert client.get('/api/admin/scanners/'+scanner_id+'/test').json()['capabilities']['modes']==['Color','Gray']
    second=client.patch('/api/admin/scanners/'+scanner_id,json={'ip':'192.0.2.125','name':'Renamed Samsung'})
    assert second.status_code==200,second.text
    assert second.json()['id']==scanner_id
    assert '192.0.2.125' in conf.read_text()
    assert '192.0.2.124' not in conf.read_text()
    assert client.get('/api/scanners').json()['scanners'][0]['name']=='Renamed Samsung'
    assert client.get('/api/scanners').json()['scanners'][0]['connected'] is True
    assert client.get('/api/admin/scanners/'+scanner_id+'/test').status_code==200
    duplicate=client.post('/api/admin/scanners',json={
        'name':'Duplicate','ip':'192.0.2.125','protocol':'WSD','port':8018,'path':'/wsd/scan'})
    assert duplicate.status_code==409
    # Disable the only scanner without a replacement, then re-enable it.
    disabled=client.patch('/api/admin/scanners/'+scanner_id,json={'enabled':False})
    assert disabled.status_code==200
    assert client.get('/api/scanners').json()['default'] is None
    assert 'Renamed Samsung' not in conf.read_text()
    enabled=client.patch('/api/admin/scanners/'+scanner_id,json={'enabled':True})
    assert enabled.status_code==200
    assert client.get('/api/scanners').json()['default']==scanner_id
    assert '192.0.2.125' in conf.read_text()
    # Remove the only default device as an admin; the registry returns to empty.
    removed=client.delete('/api/admin/scanners/'+scanner_id)
    assert removed.status_code==200,removed.text
    assert client.get('/api/scanners').json()['scanners']==[]
    assert client.get('/api/scanners').json()['default'] is None
    assert '192.0.2.125' not in conf.read_text()


def test_scanner_registry_survives_application_startup(fresh):
    client,tmp=fresh
    payload={'name':'Samsung M2885FW','ip':'192.0.2.124','protocol':'WSD','port':8018,'path':'/wsd/scan'}
    assert client.post('/api/admin/scanners',json=payload).status_code==201
    before=(tmp/'managed-airscan.conf').read_text()
    web.ensure_directories()
    assert (tmp/'managed-airscan.conf').read_text()==before
    assert len(web.registry()['scanners'])==1
    assert web.registry()['scanners'][0]['ip']=='192.0.2.124'


def test_managed_legacy_original_becomes_removable(tmp_path,monkeypatch):
    monkeypatch.setattr(web,'DATA_DIR',tmp_path)
    monkeypatch.setattr(web,'JOBS_DIR',tmp_path/'jobs')
    monkeypatch.setattr(web,'PREVIEW_ROOT',tmp_path/'print-previews')
    monkeypatch.setattr(web,'DEVICE','airscan:w0:Samsung M2885FW')
    monkeypatch.setenv('SCAN_STUDIO_ADMIN_PASSWORD','legacy-admin-password-123')
    monkeypatch.setattr(devices,'listed_sane_devices',lambda: [])
    with TestClient(web.app) as client:
        token=client.post('/api/auth/login',json={'username':'admin','password':'legacy-admin-password-123'}).json()['csrf']
        client.headers['x-csrf-token']=token
        edit=client.patch('/api/admin/scanners/original',json={'ip':'192.0.2.124','protocol':'WSD', 'port':8018,'path':'/wsd/scan'})
        assert edit.status_code==200,edit.text
        assert edit.json()['kind']=='managed'
        remove=client.delete('/api/admin/scanners/original')
        assert remove.status_code==200,remove.text
        assert web.registry()['scanners']==[]
